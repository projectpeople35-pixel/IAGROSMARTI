export function getTranslation(langCode: string): TranslationStrings {
  // If specific translation is available, use it, else fallback to Hindi or English
  if (TRANSLATIONS[langCode]) {
    return TRANSLATIONS[langCode];
  }
  // For remaining 8th schedule languages (Bodo, Dogri, Maithili, Santali, Kashmiri, Nepali, Konkani, Sindhi, Manipuri),
  // return translated title headers in their native script while keeping functional terms legible
  const lang = INDIAN_LANGUAGES.find(l => l.code === langCode);
  const base = TRANSLATIONS.en;
  if (!lang) return base;

  return {
    ...base,
    appName: `AGROSMART (${lang.nativeName})`,
    appSubtitle: `${lang.nativeName} — Smart Plant Assistant`,
    home: `${lang.nativeName} Dashboard`,
    selectPlant: `${lang.nativeName} Plant Selection`,
    waterSupply: `${lang.nativeName} Water Supply & Irrigation`,
  };
}
